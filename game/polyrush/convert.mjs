// FBX -> models.js  (compact indexed triangles, material classes). Usage: node convert.mjs <dir> <out.js>
import fs from 'fs';
import * as THREE from 'three';
import {FBXLoader} from 'three/examples/jsm/loaders/FBXLoader.js';
const dir=process.argv[2],out=process.argv[3],U=2,L=new FBXLoader(),res={};   // 1 unit = 0.5 cm
// material class: 0 plain, 1 paint (tintable), 2 rear light, 3 glass, 5 red flasher, 6 blue flasher
const TINT=new Set(['Sports','Sedan','SUV','Muscle','Pickup','Roadster']);
const cls=(n,model)=>/rear lights/.test(n)?2:/windows/.test(n)?3:/flashers siren red/.test(n)?5:/flashers siren blue/.test(n)?6:
 (TINT.has(model)&&/^body /.test(n)&&!/black|white/.test(n))?1:0;
const b64=a=>Buffer.from(a.buffer,a.byteOffset,a.byteLength).toString('base64');
for(const f of fs.readdirSync(dir).filter(f=>f.endsWith('.fbx')).sort()){
 const name=f.replace('.fbx',''),b=fs.readFileSync(dir+'/'+f),o=L.parse(b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength),'');o.updateMatrixWorld(true);
 const tris=[],mats=[],mi={},v=new THREE.Vector3();let rz=0,rn=0;
 o.traverse(m=>{if(!m.isMesh)return;const g=m.geometry,p=g.attributes.position,ix=g.index,ms=[].concat(m.material),n=ix?ix.count:p.count;
  const gi=t=>{for(const q of g.groups)if(t*3>=q.start&&t*3<q.start+q.count)return q.materialIndex;return 0};
  for(let t=0;t<n/3;t++){const mt=ms[g.groups.length?gi(t):0],c='#'+mt.color.getHexString(),k=cls(mt.name,name),key=mt.name+c;
   if(!(key in mi)){mi[key]=mats.length;const col=mt.color.getHex(true?THREE.SRGBColorSpace:0);mats.push([col>>16&255,col>>8&255,col&255,k])}
   const P=[0,1,2].map(j=>{const i=ix?ix.getX(t*3+j):t*3+j;return v.fromBufferAttribute(p,i).applyMatrix4(m.matrixWorld).toArray()});
   tris.push({P,m:mi[key]});if(mats[mi[key]][3]===2){rz+=(P[0][2]+P[1][2]+P[2][2])/3;rn++}}});
 const fl=rn&&rz/rn>0?-1:1,box=new THREE.Box3();   // fl=-1: rotate 180deg about Y so the rear (tail lights) sits at -z
 for(const t of tris)for(const P of t.P){P[0]*=fl;P[2]*=fl;box.expandByPoint(v.set(...P))}
 const cx=(box.min.x+box.max.x)/2,V=[],vi=new Map(),F=[],M=[];
 const idx=P=>{const q=[(P[0]-cx)*U,(P[1]-box.min.y)*U,(P[2]-box.min.z)*U].map(Math.round),k=q.join();if(!vi.has(k)){vi.set(k,V.length/3);V.push(...q)}return vi.get(k)};
 for(const t of tris){const[a,b2,c]=t.P.map(idx);if(a===b2||b2===c||a===c)continue;
  const e1=t.P[1].map((x,i)=>x-t.P[0][i]),e2=t.P[2].map((x,i)=>x-t.P[0][i]),ny=e1[2]*e2[0]-e1[0]*e2[2];   // y of cross(e1,e2)
  const len=Math.hypot(e1[1]*e2[2]-e1[2]*e2[1],ny,e1[0]*e2[1]-e1[1]*e2[0]);if(len&&ny/len<-.85)continue; // drop underside faces
  F.push(a,b2,c);M.push(t.m)}
 const sz=box.getSize(v);
 res[name]={w:Math.round(sz.x),h:Math.round(sz.y),l:Math.round(sz.z),mt:mats,v:b64(new Int16Array(V)),f:b64(new Uint16Array(F)),m:b64(new Uint8Array(M))};
 console.log(name.padEnd(16),'verts',V.length/3,'tris',M.length,'flip',fl,'w/h/l',res[name].w,res[name].h,res[name].l)}
fs.writeFileSync(out,'/* generated by convert.mjs from the .fbx files: indexed triangles, 1 unit = 0.5 cm, +z = forward, rear at z=0, ground at y=0 */\nwindow.CARS='+JSON.stringify(res)+';\n');
console.log('wrote',out,(fs.statSync(out).size/1024|0)+' KB');
