CREATE TABLE IF NOT EXISTS arcade_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game TEXT NOT NULL,
  player_name VARCHAR(14) NOT NULL CHECK (char_length(player_name) BETWEEN 1 AND 14),
  score DOUBLE PRECISION NOT NULL CHECK (score >= 0 AND score <= 1000000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE arcade_scores
  DROP CONSTRAINT IF EXISTS arcade_scores_game_check;

ALTER TABLE arcade_scores
  ADD CONSTRAINT arcade_scores_game_check
  CHECK (game IN ('snake', 'coin', 'memory', 'polyrush'));

ALTER TABLE arcade_scores
  ALTER COLUMN score TYPE DOUBLE PRECISION
  USING score::DOUBLE PRECISION;

CREATE UNIQUE INDEX IF NOT EXISTS arcade_scores_game_normalized_name_uidx
  ON arcade_scores (game, upper(btrim(player_name::text)));

CREATE INDEX IF NOT EXISTS arcade_scores_leaderboard_idx
  ON arcade_scores (game, score, created_at);
